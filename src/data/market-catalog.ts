type Draft = {
  id: string;
  slug: string;
  name: string;
  brand: string;
  category: Product["category"];
  subcategory: string;
  description: string;
  brandStory: string;
  origin: string;
  country: string;
  abv: number;
  volumeMl?: number;
  price: number;
  compareAtPrice?: number;
  rating: number;
  reviewCount: number;
  tastingNotes: string[];
  foodPairings: string[];
  isPremium?: boolean;
  isImported?: boolean;
  tags: string[];
};

function expand(d: Draft): Product {
  const style = STYLE[d.category] ?? STYLE.whiskey;
  return {
    id: d.id,
    slug: d.slug,
    name: d.name,
    brand: d.brand,
    category: d.category,
    subcategory: d.subcategory,
    description: d.description,
    brandStory: d.brandStory,
    origin: d.origin,
    country: d.country,
    abv: d.abv,
    volumeMl: d.volumeMl ?? 750,
    price: d.price,
    compareAtPrice: d.compareAtPrice,
    rating: d.rating,
    reviewCount: d.reviewCount,
    tastingNotes: d.tastingNotes,
    foodPairings: d.foodPairings,
    cocktails: COCKTAILS[d.category] ?? COCKTAILS.whiskey,
    images:
      (imageMap as Record<string, string[]>)[d.slug] ??
      [`/products/market/${d.slug}.jpg`],
    color: style.color,
    accentColor: style.accent,
    labelColor: style.label,
    bottleHeight: style.height,
    isPremium: d.isPremium ?? false,
    isImported: d.isImported ?? d.country !== "USA",
    tags: d.tags,
  };
}

